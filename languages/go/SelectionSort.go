// Selection Sort: Finds minimum element and places it at the beginning repeatedly
// Time: O(n²), Space: O(1)

package main

import "fmt"

func selectionSort(arr []int) {
    n := len(arr)
    for i := 0; i < n; i++ {
        minIdx := i
        for j := i + 1; j < n; j++ {
            if arr[j] < arr[minIdx] {
                minIdx = j
            }
        }
        arr[i], arr[minIdx] = arr[minIdx], arr[i]
    }
}

