// Counting Sort: Counts occurrences of each value, reconstructs sorted array
// Time: O(n + k) where k is range, Space: O(k)

fn counting_sort(arr: &mut [i32]) {
    if arr.is_empty() {
        return;
    }

    let max_val = *arr.iter().max().unwrap();
    let min_val = *arr.iter().min().unwrap();
    let range = (max_val - min_val + 1) as usize;

    let mut count = vec![0; range];
    let mut output = vec![0; arr.len()];

    for &num in arr.iter() {
        count[(num - min_val) as usize] += 1;
    }

    for i in 1..count.len() {
        count[i] += count[i - 1];
    }

    for &num in arr.iter().rev() {
        let idx = (num - min_val) as usize;
        output[count[idx] - 1] = num;
        count[idx] -= 1;
    }

    arr.copy_from_slice(&output);
}

